def gen_reviews():
    reviews = []
    idx = 0
    for point, templates in SELLING_POINTS.items():
        for t in templates:
            idx += 1
            reviews.append({
                "id": f"r{idx:04d}",
                "source": "synthetic_sample",
                "product": "手游外设手柄",
                "text": t,
                "rating": 5,
                "date": "2026-10",
                "_expected_cluster": point,  # spike 验证用：标注真实卖点，检验聚类纯度
            })
    for t in NOISE:
        idx += 1
        reviews.append({
            "id": f"r{idx:04d}",
            "source": "synthetic_sample",
            "product": "手游外设手柄",
            "text": t,
            "rating": None,
            "date": "2026-10",
            "_expected_cluster": None,  # 噪声，不该进卖点簇
        })
    random.shuffle(reviews)
    return reviews

